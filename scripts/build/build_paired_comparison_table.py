"""Summarize paired errors from saved targets; never generate new simulations."""

from __future__ import annotations

import csv
import hashlib
import json
import math
import statistics
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
TABLE = ROOT / "docs/paper/overleaf/experiments/causal_atlas_bridge/tables/app_paired_comparison.tex"
AUDIT = ROOT / "docs/paper/revision_evidence/paired_comparison_audit.json"


def main() -> None:
    source = ROOT / "results/certificate_diagnostics_summary.csv"
    with source.open(newline="", encoding="utf-8") as stream:
        records = list(csv.DictReader(stream))
    if len({row["seed"] for row in records}) != len(records):
        raise ValueError("Expected distinct archive-target simulation seeds")
    atlas = [float(row["atlas_no_rejection_absolute_error"]) for row in records]
    z = statistics.NormalDist().inv_cdf(0.975)
    rows = []
    for method, label in (
        ("semantic_forced", "Semantic forced"),
        ("nearest_semantic", "Nearest semantic"),
        ("global_mean", "Global mean"),
        ("oracle_latent_support", r"Oracle latent support$^{\dagger}$"),
    ):
        differences = [float(row[method + "_absolute_error"]) - error for row, error in zip(records, atlas)]
        mean = statistics.mean(differences)
        se = statistics.stdev(differences) / math.sqrt(len(differences))
        rows.append({"method": method, "label": label, "targets": len(differences),
                     "mean_paired_difference": mean, "mcse": se,
                     "normal_95_mc_interval": [mean - z * se, mean + z * se]})
    lines = [
        r"% Generated by scripts/build/build_paired_comparison_table.py from saved targets.",
        r"\begin{table}[H]",
        r"\centering",
        r"\small",
        r"\caption{Paired absolute-error differences on the 300 common synthetic targets. Each comparator and no-rejection ATLAS are evaluated on all targets. Positive differences favor no-rejection ATLAS.}",
        r"\label{tab:v1-app-paired-comparison}",
        r"\begin{tabular}{lrrr}",
        r"\toprule",
        r"Comparator & Mean difference & MC SE & 95\% MC interval \\",
        r"\midrule",
    ]
    for row in rows:
        lo, hi = row["normal_95_mc_interval"]
        lines.append(f"{row['label']} & {row['mean_paired_difference']:.4f} & {row['mcse']:.4f} & $[{lo:.4f}, {hi:.4f}]$ " + r"\\")
    lines += [
        r"\bottomrule",
        r"\end{tabular}",
        r"\par\smallskip",
        r"\begin{minipage}{0.96\linewidth}\footnotesize",
        r"For target $i$, $d_i$ is the comparator's absolute error minus the no-rejection ATLAS absolute error. MC SE is $s_d/\sqrt{300}$; the normal-approximation interval is $\bar d\pm1.96\,\mathrm{MC\,SE}$. It summarizes Monte Carlo uncertainty in the mean difference under the fixed synthetic protocol. $^{\dagger}$The latent oracle is evaluation-only.",
        r"\end{minipage}",
        r"\end{table}",
    ]
    TABLE.write_text("\n".join(lines) + "\n", encoding="utf-8")
    audit = {"source": source.relative_to(ROOT).as_posix(),
             "source_sha256": hashlib.sha256(source.read_bytes()).hexdigest(),
             "reference": "atlas_no_rejection", "repetitions": len(records),
             "mcse_definition": "sample standard deviation of paired differences / sqrt(n)",
             "normal_quantile": z, "rows": rows,
             "table_sha256": hashlib.sha256(TABLE.read_bytes()).hexdigest()}
    AUDIT.write_text(json.dumps(audit, indent=2) + "\n", encoding="utf-8")
    print(f"Built {TABLE.name} from {len(records)} saved paired targets.")


if __name__ == "__main__":
    main()
