"""Run target-level certificate diagnostics and the synthetic benchmark."""

from __future__ import annotations

import csv
import json
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(PROJECT_ROOT / "src"))

from causal_atlas_sim.certificate_diagnostics import (
    CertificateDiagnosticsConfig,
    run_certificate_diagnostics,
)

RESULTS_DIR = PROJECT_ROOT / "results"
TABLES_DIR = RESULTS_DIR / "tables"
METHOD_LABELS = {
    "atlas": "Causal ATLAS",
    "atlas_no_rejection": "ATLAS, no rejection",
    "semantic_forced": "Semantic forced",
    "nearest_semantic": "Nearest semantic",
    "global_mean": "Global mean",
    "oracle_latent_support": "Oracle latent support*",
}


def main() -> None:
    result = run_certificate_diagnostics(CertificateDiagnosticsConfig())
    RESULTS_DIR.mkdir(exist_ok=True)
    TABLES_DIR.mkdir(exist_ok=True)
    diagnostic_values = [record.as_dict() for record in result.records]
    benchmark_values = [row.as_dict() for row in result.benchmark_rows]
    diagnostic_path = RESULTS_DIR / "certificate_diagnostics_summary.csv"
    benchmark_path = RESULTS_DIR / "synthetic_benchmark_summary.csv"
    _write_csv(diagnostic_path, diagnostic_values)
    _write_csv(benchmark_path, benchmark_values)
    metadata_path = RESULTS_DIR / "certificate_diagnostics_metadata.json"
    metadata_path.write_text(
        json.dumps(result.to_dict(), ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    _write_benchmark_tables(benchmark_values)
    print(
        json.dumps(
            {
                "target_records": len(result.records),
                "benchmark_methods": len(result.benchmark_rows),
                "spearman": result.spearman_correlation,
                "error_exceeds_certificate_rate": result.error_exceeds_certificate_rate,
                "diagnostics": str(diagnostic_path),
                "benchmark": str(benchmark_path),
                "metadata": str(metadata_path),
            },
            ensure_ascii=False,
            indent=2,
        )
    )


def _write_csv(path: Path, rows: list[dict]) -> None:
    with path.open("w", newline="", encoding="utf-8") as output:
        writer = csv.DictWriter(output, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)


def _write_benchmark_tables(rows: list[dict]) -> None:
    markdown = [
        "# Synthetic benchmark with evaluation-only oracle",
        "",
        "ATLAS 行的误差、覆盖率和宽度以实际发布目标为条件；其余强制发布方法",
        "在全部共同目标上评价。因此发布率必须与条件误差一起解释。",
        "",
        "| Method | Release | MAE | RMSE | Sign | Coverage | Width |",
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    for row in rows:
        markdown.append(
            f"| {METHOD_LABELS[row['method']]} | {row['release_rate']:.4f} | "
            f"{_f(row['mae'])} | {_f(row['rmse'])} | {_f(row['sign_accuracy'])} | "
            f"{_f(row['interval_coverage'])} | {_f(row['mean_interval_width'])} |"
        )
    markdown.extend(
        [
            "",
            "* Oracle latent support 使用仿真中不可被估计器观察的真实机制坐标，",
            "  仅作为评价上界参考，不参与任何可部署方法的检索、权重、拒绝或 bridge 选择。",
        ]
    )
    (TABLES_DIR / "main_synthetic_table.md").write_text(
        "\n".join(markdown) + "\n",
        encoding="utf-8",
    )
    latex = [
        "% Generated by scripts/run/run_certificate_diagnostics.py; do not edit.",
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{Synthetic benchmark with an evaluation-only latent-support oracle.}",
        "\\label{tab:main-synthetic}",
        "\\begin{tabular}{lrrrrrr}",
        "\\toprule",
        "Method & Release & MAE & RMSE & Sign & Coverage & Width \\\\",
        "\\midrule",
    ]
    for row in rows:
        label = METHOD_LABELS[row["method"]].replace("*", "$^{\\dagger}$")
        latex.append(
            f"{label} & {row['release_rate']:.3f} & {_f(row['mae'], 3)} & "
            f"{_f(row['rmse'], 3)} & {_f(row['sign_accuracy'], 3)} & "
            f"{_f(row['interval_coverage'], 3)} & {_f(row['mean_interval_width'], 3)} \\\\"
        )
    latex.extend(
        [
            "\\bottomrule",
            "\\end{tabular}",
            "\\begin{minipage}{0.96\\linewidth}\\footnotesize",
            "$^{\\dagger}$ Uses simulated latent mechanisms unavailable to the estimator and is included only as an evaluation reference.",
            "\\end{minipage}",
            "\\end{table}",
        ]
    )
    (TABLES_DIR / "main_synthetic_table.tex").write_text(
        "\n".join(latex) + "\n",
        encoding="utf-8",
    )


def _f(value, digits: int = 4) -> str:
    return "NA" if value is None else f"{value:.{digits}f}"


if __name__ == "__main__":
    main()
